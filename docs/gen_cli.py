"""Write docs/cli.md from the `--help` output of every console script.

    python docs/gen_cli.py

Run it from the package root after `pip install -e .`, and commit the result. It reads the
command list from `[project.scripts]` in pyproject.toml, runs `<command> --help` (and
`<command> <subcommand> --help` for commands with subcommands), and writes one section per
command.

Only the usage line, the first line of the description and the argument list are kept. The
rest of each description is module background written for the original project, so read it
with `--help` in a terminal.
"""
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "docs", "cli.md")

# Lines that start a section of argparse output. Everything between the usage block and the
# first of these is the description.
SECTION = re.compile(r"^(positional arguments|options|optional arguments):\s*$")


def scripts():
    """The console scripts named in pyproject.toml, in file order."""
    with open(os.path.join(ROOT, "pyproject.toml"), encoding="utf-8") as handle:
        text = handle.read()
    block = text.split("[project.scripts]", 1)[1].split("\n[", 1)[0]
    return [m.group(1) for m in re.finditer(r"^\s*([\w-]+)\s*=", block, re.MULTILINE)]


def find(command):
    """Prefer the copy beside the running interpreter (the active virtual environment)."""
    local = os.path.join(os.path.dirname(sys.executable), command)
    return local if os.path.exists(local) else shutil.which(command)


def run_help(argv):
    env = dict(os.environ, COLUMNS="100")
    # Some commands check for the salt on start-up. A placeholder is enough for --help.
    env.setdefault("EWL_AUTHOR_SALT", "docs-placeholder-salt")
    proc = subprocess.run(argv + ["--help"], capture_output=True, text=True, env=env)
    if proc.returncode != 0:
        raise SystemExit(f"{' '.join(argv)} --help failed:\n{proc.stderr}")
    return proc.stdout


def trim(help_text):
    """Usage, the description's first line, and the argument sections."""
    lines = help_text.rstrip().splitlines()
    usage = []
    i = 0
    while i < len(lines) and lines[i].strip():
        usage.append(lines[i])
        i += 1
    while i < len(lines) and not lines[i].strip():
        i += 1
    summary = ""
    rest = []
    in_description = True
    summary_open = True
    for line in lines[i:]:
        if in_description and SECTION.match(line):
            in_description = False
        if in_description:
            # The first paragraph, up to a blank or indented line (usually an example).
            if summary_open and line.strip() and not line[:1].isspace():
                summary = f"{summary} {line.strip()}".strip()
            elif summary:
                summary_open = False
            continue
        rest.append(line)
    if len(summary) > 250 and ". " in summary:
        summary = summary.split(". ", 1)[0] + "."
    return "\n".join(usage), summary, "\n".join(rest).strip()


def subcommands(help_text):
    """Subcommand names, when the command uses argparse subparsers (they are listed one per
    line under the {a,b,c} line); [] for a plain positional choice."""
    lines = help_text.splitlines()
    for n, line in enumerate(lines):
        if re.match(r"^\s+\{[\w,-]+\}\s*$", line):
            names = line.strip()[1:-1].split(",")
            # Subparsers list each name on its own line, indented four spaces; a wrapped
            # description continues further in, so only the four-space lines count.
            listed = [m.group(1) for l in lines[n + 1:]
                      for m in [re.match(r"^    (\S+)", l)] if m]
            return names if all(name in listed for name in names) else []
    return []


def section(argv, level, executable):
    text = run_help([executable] + argv[1:])
    usage, summary, rest = trim(text)
    out = [f"{'#' * level} `{' '.join(argv)}`", ""]
    if summary:
        out += [summary, ""]
    out += ["```text", usage, "", rest, "```", ""]
    return out, text


def main():
    out = [
        "# Command reference",
        "",
        "<!-- Generated by docs/gen_cli.py. Do not edit by hand: run "
        "`python docs/gen_cli.py` and commit the result. -->",
        "",
        "This page is generated from each command's `--help` output by `docs/gen_cli.py`. "
        "It keeps the usage line, the first line of the description and the arguments. "
        "Run the command with `--help` for the full description.",
        "",
        "Every command also runs as `python -m <module>`; the module for each is in "
        "`[project.scripts]` in `pyproject.toml`.",
        "",
    ]
    for name in scripts():
        path = find(name)
        if not path:
            raise SystemExit(f"{name} is not installed. Run `pip install -e .` first.")
        lines, text = section([name], 2, path)
        out += lines
        for sub in subcommands(text):
            sub_lines, _ = section([name, sub], 3, path)
            out += sub_lines
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out).rstrip() + "\n")
    print(f"Wrote {os.path.relpath(OUTPUT, ROOT)}")


if __name__ == "__main__":
    main()
